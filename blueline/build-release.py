#!/usr/bin/env python3
"""Publish the six-page BlueLine source and only its runtime dependencies."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit, unquote
import argparse
import hashlib
import json
import posixpath
import re
import shutil

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'system1-mirror/site'
PAGES = ['index.html', 'contact.html', 'terms/privacy-policy.html', 'terms/terms-of-use.html', 'terms/copyright.html', 'terms/privacy-policy/privacy-inquiries.html']
URL = re.compile(r'url\(\s*([\"\x27]?)(.*?)\1\s*\)', re.S)

def local(value, owner):
    url = urlsplit(value)
    if url.scheme or url.netloc or not url.path:
        return None
    path = unquote(url.path)
    resolved = posixpath.normpath(path.lstrip('/') if path.startswith('/') else posixpath.join(posixpath.dirname(owner), path))
    if resolved.startswith('../'):
        raise ValueError(f'Asset escapes release: {value}')
    return resolved

class Assets(HTMLParser):
    def __init__(self, owner):
        super().__init__(); self.owner = owner; self.paths = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        names = ['src'] if tag in ['img','script','source','iframe','image'] else ['href'] if tag == 'link' and attrs.get('rel') == 'stylesheet' else []
        for name in names:
            if attrs.get(name):
                path = local(attrs[name], self.owner)
                if path: self.paths.append(path)
        for _, value in URL.findall(attrs.get('style', '')):
            path = local(value, self.owner)
            if path: self.paths.append(path)

def build(destination):
    selected = set(PAGES)
    pending = list(PAGES)
    while pending:
        name = pending.pop()
        path = SOURCE/name
        if not path.is_file():
            raise FileNotFoundError(f'Missing release asset: {name}')
        deps = []
        if path.suffix == '.html':
            text = path.read_text(); parser = Assets(name); parser.feed(text); deps += parser.paths
            deps += [p for _, value in URL.findall(text) if (p := local(value, name))]
        elif path.suffix == '.css':
            deps += [p for _, value in URL.findall(path.read_text()) if (p := local(value, name))]
        for dep in deps:
            if dep not in selected: selected.add(dep); pending.append(dep)
    if (SOURCE/'image-sources.json').exists(): selected.add('image-sources.json')
    # Keep the downloaded mirror out of version control except this exact source set.
    directories=set()
    for name in selected:
        directories.update(parent.as_posix() for parent in Path(name).parents if parent.as_posix()!='.')
    rules=['# Generated by blueline/build-release.py: runtime source files only.','/*','!/.gitignore']
    for directory in sorted(directories,key=lambda value:(value.count('/'),value)):
        rules += ['!/'+directory+'/', '/'+directory+'/*']
    rules += ['!/'+name for name in sorted(selected)]
    (SOURCE/'.gitignore').write_text('\n'.join(rules)+'\n')
    for name in sorted(selected):
        target=destination/name;target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(SOURCE/name,target)
    manifest = {'pages': PAGES, 'files': sorted(selected), 'sha256': {name:hashlib.sha256((destination/name).read_bytes()).hexdigest() for name in sorted(selected)}}
    (destination/'release-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Release: {len(selected)} files, {sum((destination/p).stat().st_size for p in selected):,} bytes')
    return manifest

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT)
    args=parser.parse_args()
    build(args.output.resolve())
